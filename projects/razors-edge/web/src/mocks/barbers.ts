function buildBarber(seed: BarberSeed): Barber {
  const bio = BARBER_BIOS[seed.id] ?? `${seed.name}, a Razor's Edge barber.`;

  return barberSchema.parse({
    id: seed.id,
    slug: seed.slug,
    name: seed.name,
    handle: seed.handle,
    title: seed.title,
    bio,
    specialties: seed.specialties,
    serviceIds: serviceIdsFor(seed.specialties),
    portrait: {
      slot: `barber-${seed.slug}`,
      src: `/images/graded/barber-${seed.slug}.jpg`,
      alt: `${seed.name}, ${seed.title} at Razor's Edge`,
      aspectRatio: seed.portraitAspect,
      blurDataURL:
        BLUR_PLACEHOLDERS[
          `barber-${seed.slug}` as keyof typeof BLUR_PLACEHOLDERS
        ],
    },
    workingHours: seed.workingHours,
    daysOff: seed.daysOff,
    ...(seed.lunch ? { lunch: seed.lunch } : {}),
  });
}

/** The validated, frozen roster. */
export const BARBERS: readonly Barber[] = Object.freeze(
  RAW_BARBERS.map(buildBarber),
);

export function getBarberById(id: string): Barber | undefined {
  return BARBERS.find((b) => b.id === id);
}

export function getBarberBySlug(slug: string): Barber | undefined {
  return BARBERS.find((b) => b.slug === slug);
}

/** Barbers who perform a given service category (wizard barber filtering). */
export function barbersForCategory(
  category: Barber['specialties'][number],
): Barber[] {
  return BARBERS.filter((b) => b.specialties.includes(category));
}
