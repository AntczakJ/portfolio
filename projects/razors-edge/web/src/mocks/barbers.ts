/**
 * The fixed Razor's Edge barber roster (ADR-003 / PLAN.md).
 *
 * Identities, specialties, working hours, days-off, and lunch are
 * hand-curated so the roster reads as a real team with distinct schedules
 * (giving the availability grid believable gaps). Faker — seeded for
 * determinism (docs/conventions.md § 6) — fills ONLY the bio flavour copy.
 *
 * Days-off are pinned to concrete dates inside the frozen "next 14 days"
 * window (frozen now = Wed 2026-06-10) so the grid shows real day-off
 * holes deterministically.
 *
 * `serviceIds` are derived from each barber's `specialties` against the
 * fixed menu, so a barber's bookable services always stay consistent with
 * what they specialise in.
 *
 * The bios were generated by faker (seed 74017) at build time and BAKED into
 * the static `seed-data.ts` module (`BARBER_BIOS`). faker is NOT imported
 * here at runtime — it uses `new Function`/`eval` internally, which the
 * strict CSP blocks, and this module is reached by the booking wizard's
 * client components. The baked bios are byte-identical to the seeded output.
 */

/** Indexed 0 = Sun … 6 = Sat (matches WeeklySchedule / clock weekday). */
function schedule(
  rows: Partial<Record<number, { open: string; close: string }>>,
): WeeklySchedule {
  const day = (i: number) => rows[i] ?? null;
  return [day(0), day(1), day(2), day(3), day(4), day(5), day(6)];
}

