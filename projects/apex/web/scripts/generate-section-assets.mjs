let P = PALETTES.light;

async function render(svg, outPath, width, height, { fit = 'cover' } = {}) {
  await mkdir(dirname(outPath), { recursive: true });
  await sharp(Buffer.from(svg), { density: 200 })
    .resize(width, height, { fit })
    .avif({ quality: 60, effort: 6 })
    .toFile(outPath);
}

/* =========================================================================
 * Fleet vehicle renders — one consistent STUDIO FAMILY (A-02). All four
 * non-flagship cars share the flagship GLB frame's treatment: a 3/4-front
 * studio pose on a seamless cyclorama (floor-to-wall gradient sweep), a soft
 * key-light vignette, an elliptical contact shadow, and a floor reflection.
 * They are distinguished by SEGMENT / PROPORTION (sedan / suv / coupe /
 * compact) — roofline height, length, stance, wheel size — NOT by a different
 * art style. No flat 2-tone fills, no accent underline gimmick, no watermark
 * (A-03). The result reads as one line-up shot in the same studio.
 *
 * Geometry: a believable 3/4-front projection. The body is drawn as a near-side
 * flank plus a foreshortened front face (hood + bumper + grille), with the far
 * side hinted. Two wheels are visible: the near-front wheel is larger and lower,
 * the near-rear smaller and set back. A faked perspective gives it depth without
 * a true 3D render.
 * ===================================================================== */
function fleetSvg({ width, height, archetype, paint, paintSpec, paintShade }) {
  // Per-archetype proportions (relative to the car width `W`). Tuned so the
  // segments read distinctly: a low/long performance coupe, a tall/boxier SUV,
  // a long-bonnet sedan, a short compact.
  const profiles = {
    compact: { len: 0.82, roof: 0.42, beltY: 0.5, wheel: 0.16, front: 0.2 },
    sedan: { len: 1.12, roof: 0.34, beltY: 0.54, wheel: 0.14, front: 0.22 },
    suv: { len: 1.02, roof: 0.62, beltY: 0.44, wheel: 0.18, front: 0.24 },
    performance: { len: 1.14, roof: 0.26, beltY: 0.6, wheel: 0.15, front: 0.2 },
  };
  const pr = profiles[archetype] ?? profiles.sedan;

  const cx = width / 2;
  const baseY = height * 0.72; // ground contact line
  const W = width * 0.58 * pr.len;
  const carH = W * 0.34;
  // The near flank runs left (rear) -> right (front face turned toward us).
  const xRear = cx - W * 0.46;
  const xFrontFace = cx + W * 0.5; // the foreshortened nose
  const bodyTop = baseY - carH;
  const roofH = carH * pr.roof;
  const roofY = bodyTop - roofH;
  const beltY = baseY - carH * pr.beltY;

  // Near flank silhouette (a smooth premium body line).
  const flank = `M ${xRear} ${baseY}
    C ${xRear - W * 0.02} ${beltY + carH * 0.1}, ${xRear + W * 0.02} ${bodyTop + carH * 0.05}, ${xRear + W * 0.16} ${bodyTop}
    C ${xRear + W * 0.3} ${roofY + roofH * 0.15}, ${xRear + W * 0.42} ${roofY}, ${cx} ${roofY}
    C ${cx + W * 0.18} ${roofY}, ${cx + W * 0.3} ${roofY + roofH * 0.25}, ${cx + W * 0.42} ${bodyTop + carH * 0.04}
    L ${xFrontFace} ${bodyTop + carH * 0.16}
    C ${xFrontFace + W * 0.03} ${beltY}, ${xFrontFace + W * 0.02} ${baseY - carH * 0.18}, ${xFrontFace - W * 0.02} ${baseY}
    Z`;

  // The foreshortened front face (hood + bumper), a touch darker for the turn.
  const front = `M ${cx + W * 0.42} ${bodyTop + carH * 0.04}
    L ${xFrontFace} ${bodyTop + carH * 0.16}
    C ${xFrontFace + W * 0.03} ${beltY}, ${xFrontFace + W * 0.02} ${baseY - carH * 0.18}, ${xFrontFace - W * 0.02} ${baseY}
    L ${cx + W * 0.4} ${baseY}
    C ${cx + W * 0.44} ${beltY + carH * 0.1}, ${cx + W * 0.44} ${bodyTop + carH * 0.3}, ${cx + W * 0.42} ${bodyTop + carH * 0.04}
    Z`;

  // Glasshouse (the greenhouse over the belt line).
  const glass = `M ${xRear + W * 0.2} ${bodyTop + carH * 0.02}
    C ${xRear + W * 0.32} ${roofY + roofH * 0.3}, ${xRear + W * 0.44} ${roofY + roofH * 0.18}, ${cx} ${roofY + roofH * 0.18}
    C ${cx + W * 0.14} ${roofY + roofH * 0.18}, ${cx + W * 0.26} ${roofY + roofH * 0.35}, ${cx + W * 0.36} ${beltY - carH * 0.04}
    L ${xRear + W * 0.24} ${beltY - carH * 0.04} Z`;

  // Wheels (near-front larger + lower, near-rear set back). Arches matched.
  const wR = carH * pr.wheel * 3.2;
  const fwx = cx + W * 0.28;
  const rwx = xRear + W * 0.12;
  const wheel = (wx, r) => `
    <ellipse cx="${wx}" cy="${baseY + r * 0.04}" rx="${r * 1.04}" ry="${r}" fill="${P.ink}"/>
    <ellipse cx="${wx}" cy="${baseY + r * 0.04}" rx="${r * 0.62}" ry="${r * 0.6}" fill="#2a313b"/>
    <ellipse cx="${wx}" cy="${baseY + r * 0.04}" rx="${r * 0.2}" ry="${r * 0.2}" fill="#3c4650"/>`;

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
  <defs>
    <linearGradient id="cyc" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${P.wallTop}"/>
      <stop offset="0.55" stop-color="${P.wallBottom}"/>
      <stop offset="0.62" stop-color="${P.floorTop}"/>
      <stop offset="1" stop-color="${P.floorBottom}"/>
    </linearGradient>
    <radialGradient id="key" cx="0.5" cy="0.32" r="0.7"><stop offset="0" stop-color="${P.keylight}" stop-opacity="0.5"/><stop offset="1" stop-color="${P.keylight}" stop-opacity="0"/></radialGradient>
    <linearGradient id="paint" x1="0.1" y1="0" x2="0.4" y2="1"><stop offset="0" stop-color="${paintSpec}"/><stop offset="0.4" stop-color="${paint}"/><stop offset="1" stop-color="${paintShade}"/></linearGradient>
    <linearGradient id="paintFront" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${paint}"/><stop offset="1" stop-color="${paintShade}"/></linearGradient>
    <radialGradient id="contact" cx="0.5" cy="0.5" r="0.5"><stop offset="0" stop-color="${P.contactInk}" stop-opacity="0.5"/><stop offset="0.65" stop-color="${P.contactInk}" stop-opacity="0.14"/><stop offset="1" stop-color="${P.contactInk}" stop-opacity="0"/></radialGradient>
    <linearGradient id="refl" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="${paint}" stop-opacity="0.22"/><stop offset="1" stop-color="${paint}" stop-opacity="0"/></linearGradient>
  </defs>

  <!-- Seamless studio cyclorama (floor-to-wall sweep). -->
  <rect x="0" y="0" width="${width}" height="${height}" fill="url(#cyc)"/>
  <rect x="0" y="0" width="${width}" height="${height}" fill="url(#key)"/>

  <!-- Floor reflection of the body (mirrored, faded). -->
  <g transform="translate(0 ${baseY * 2}) scale(1 -1)">
    <path d="${flank}" fill="url(#refl)"/>
  </g>

  <!-- Contact shadow. -->
  <ellipse cx="${cx}" cy="${baseY + carH * 0.07}" rx="${W * 0.56}" ry="${carH * 0.13}" fill="url(#contact)"/>

  <!-- Body: near flank + foreshortened front face. -->
  <path d="${flank}" fill="url(#paint)"/>
  <path d="${front}" fill="url(#paintFront)"/>
  <!-- A single soft specular sweep along the shoulder (premium sheen). -->
  <path d="M ${xRear + W * 0.16} ${beltY - carH * 0.08} C ${cx} ${beltY - carH * 0.14}, ${cx + W * 0.2} ${beltY - carH * 0.1}, ${cx + W * 0.36} ${beltY - carH * 0.02}" stroke="${paintSpec}" stroke-width="${carH * 0.04}" stroke-linecap="round" fill="none" opacity="0.5"/>

  <!-- Glasshouse. -->
  <path d="${glass}" fill="${P.ink}" opacity="0.78"/>
  <path d="${glass}" fill="${paintSpec}" opacity="0.06"/>

  <!-- Headlight signature (one restrained accent, like the GLB rim graze). -->
  <ellipse cx="${xFrontFace - W * 0.02}" cy="${beltY}" rx="${W * 0.02}" ry="${carH * 0.05}" fill="${P.accent}" opacity="0.7"/>

  ${wheel(rwx, wR * 0.92)}
  ${wheel(fwx, wR)}
</svg>`;
}

/* =========================================================================
 * Static maps — styled static-map treatments (NO live embed). A clean,
 * on-brand abstract map with an accent pin at centre. Per location + theme.
 * ===================================================================== */
function mapSvg({ width, height, kind }) {
  const cx = width * 0.5;
  const cy = height * 0.46;
  // Pseudo-random-but-deterministic block layout from the kind string.
  const seed = [...kind].reduce((a, c) => a + c.charCodeAt(0), 0);
  const rng = (n) => {
    const x = Math.sin(seed * 9301 + n * 49297) * 233280;
    return x - Math.floor(x);
  };
  const blocks = [...Array(26)].map((_, i) => {
    const bx = rng(i) * width;
    const by = rng(i + 100) * height;
    const bw = 20 + rng(i + 200) * 80;
    const bh = 18 + rng(i + 300) * 60;
    const fill = rng(i + 400) > 0.5 ? P.landA : P.landB;
    return `<rect x="${bx}" y="${by}" width="${bw}" height="${bh}" rx="3" fill="${fill}"/>`;
  }).join('');
  const roads = [
    `<rect x="0" y="${height * 0.3}" width="${width}" height="6" fill="${P.road}" opacity="0.7"/>`,
    `<rect x="0" y="${height * 0.66}" width="${width}" height="8" fill="${P.road}" opacity="0.7"/>`,
    `<rect x="${width * 0.34}" y="0" width="6" height="${height}" fill="${P.road}" opacity="0.7"/>`,
    `<rect x="${width * 0.72}" y="0" width="7" height="${height}" fill="${P.road}" opacity="0.7"/>`,
  ].join('');
  const water =
    kind === 'airport'
      ? `<rect x="0" y="${height * 0.78}" width="${width}" height="${height * 0.22}" fill="${P.water}" opacity="0.85"/>`
      : '';
  const runway =
    kind === 'airport'
      ? `<rect x="${width * 0.1}" y="${height * 0.85}" width="${width * 0.5}" height="5" rx="2.5" fill="${P.road}" opacity="0.6" transform="rotate(-8 ${width * 0.3} ${height * 0.87})"/>`
      : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
  <rect x="0" y="0" width="${width}" height="${height}" fill="${P.mapBg ?? P.bg}"/>
  ${blocks}
  ${water}
  ${roads}
  ${runway}
  <!-- accent pin -->
  <circle cx="${cx}" cy="${cy}" r="${width * 0.06}" fill="${P.accent}" opacity="0.18"/>
  <path d="M ${cx} ${cy + 26} C ${cx - 16} ${cy - 4}, ${cx - 14} ${cy - 22}, ${cx} ${cy - 22} C ${cx + 14} ${cy - 22}, ${cx + 16} ${cy - 4}, ${cx} ${cy + 26} Z" fill="${P.accent}"/>
  <circle cx="${cx}" cy="${cy - 13}" r="6" fill="${P.pinRing}"/>
</svg>`;
}

async function main() {
  // NOTE (model-swap PASS B): the fleet renders are NO LONGER generated here —
  // they come from the live R3F scene via `render-from-scene.mjs` (one studio
  // line-up with the flagship; closes N-1). `fleetSvg()` is retained above for
  // reference only. This script now produces the static maps only.

  // ----- Static maps (per location, both registers) ------------------------
  const maps = [
    { slug: 'lisbon-airport', kind: 'airport' },
    { slug: 'lisbon-baixa', kind: 'city' },
    { slug: 'porto-airport', kind: 'airport' },
    { slug: 'porto-depot', kind: 'depot' },
  ];
  for (const reg of ['light', 'dark']) {
    P = PALETTES[reg];
    const suffix = reg === 'dark' ? '-dark' : '';
    for (const m of maps) {
      const svg = mapSvg({ width: 800, height: 600, kind: m.kind });
      await render(svg, join(PUBLIC, 'maps', `${m.slug}${suffix}.avif`), 800, 600);
    }
  }

  console.log(
    `Generated ${maps.length} static maps (light + dark) into public/. ` +
      `Fleet renders + gallery crops now come from the live GLB scene via render-from-scene.mjs.`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
