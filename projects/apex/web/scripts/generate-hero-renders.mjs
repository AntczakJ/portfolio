/**
 * generate-hero-renders.mjs — on-brand PLACEHOLDER product renders (Task 4.2).
 *
 * apex's mock data references `/renders/lumen-gt/hero.avif` (the LCP static
 * render the scroll-hero hands off from) and the colour x wheel matrix stills.
 * The real renders come from the royalty-clear GLB + the shared camera/lighting
 * rig in Tasks 4.3/4.4 ("one rig, three outputs"). Until that lands, this
 * script generates a tasteful, clearly-marked on-brand placeholder so the hero
 * paints a real, legible studio frame (never a broken image) and the LCP slot
 * is held CLS-safely.
 *
 * It is a self-contained Node script using `sharp` (a devDependency) to
 * rasterise an SVG studio composition to AVIF — no external imagery is
 * fetched, so it works offline and carries no licensing exposure. The output
 * is committed under `public/renders/` and is the thing the swap-for-real pass
 * (Task 4.3/4.4) replaces.
 *
 * Run: `pnpm -F apex-web renders:placeholder`
 *
 * PROVENANCE: 100% generated by this script (CC0 / no third-party asset).
 * Recorded in CREDITS.md + AGENT_NOTES.md. The voltaic-green accent + the
 * cool studio light match the apex tokens (globals.css Task 2.1).
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import sharp from 'sharp';

const HERE = dirname(fileURLToPath(import.meta.url));
const RENDERS_DIR = join(HERE, '..', 'public', 'renders', 'lumen-gt');

/**
 * apex token palettes (kept in sync with globals.css). The configurator stills
 * are rendered for BOTH the light register AND the dark "night drive / charging-
 * bay" register — a RE-KEY, not an inversion (ADR-001) — so the dark theme is a
 * night studio (deep cool stage, lifted floor glow, the brighter accent), not a
 * light car floating on a dark page (the Task 4.2 AGENT_NOTES finding).
 */
const PALETTES = {
  light: {
    floorTop: '#f7f9fb',
    floorBottom: '#e7ecf1',
    wallTop: '#eef2f6',
    wallBottom: '#dde4ea',
    keylight: '#ffffff',
    ink: '#10151c',
    accent: '#18c08a',
    contactInk: '#10151c',
    rimSpec: 0.5,
  },
  dark: {
    floorTop: '#11161f',
    floorBottom: '#070a0f',
    wallTop: '#161d28',
    wallBottom: '#0a0e14',
    keylight: '#9fb6c9',
    ink: '#04070b',
    accent: '#2ee6a6',
    contactInk: '#000000',
    rimSpec: 0.7,
  },
};

/** Active palette (set per render pass). */
let PALETTE = PALETTES.light;

/** The four configurable paints (matches seed-data colours). */
const COLORS = {
  'col-glacier': { body: '#eef1f4', shade: '#d3d9df', spec: '#ffffff', name: 'Glacier White' },
  'col-graphite': { body: '#2b313a', shade: '#171b21', spec: '#5a6470', name: 'Graphite' },
  'col-voltaic': { body: '#18c08a', shade: '#0c8a62', spec: '#7df2cf', name: 'Voltaic Green' },
  'col-midnight': { body: '#16243f', shade: '#0c1426', spec: '#3a5b91', name: 'Midnight Blue' },
};

/** Wheel face treatment (matches seed-data wheels). */
const WHEELS = {
  'whl-aero': { spokes: 0, name: 'Aero 20"' }, // smooth aero cover
  'whl-turbine': { spokes: 10, name: 'Turbine 21"' },
  'whl-forged': { spokes: 5, name: 'Forged 22"' },
};

/**
 * Build an SVG of a stylised, low-poly "concept EV" coupe in a studio.
 * Deliberately abstract (no manufacturer geometry / badge) — it reads as a
 * premium silhouette and is unmistakably a placeholder, not a real photo.
 */
function studioSvg({ width, height, color, wheel, label }) {
  const c = COLORS[color] ?? COLORS['col-glacier'];
  const w = WHEELS[wheel] ?? WHEELS['whl-aero'];

  // Car footprint centred in the lower-middle of the frame.
  const cx = width / 2;
  const baseY = height * 0.66;
  const carW = width * 0.66;
  const carH = carW * 0.3;
  const x0 = cx - carW / 2;

  // Wheel geometry.
  const wheelR = carH * 0.34;
  const frontWX = x0 + carW * 0.24;
  const rearWX = x0 + carW * 0.78;
  const wheelY = baseY;

  const spokes = (wx) => {
    if (w.spokes === 0) {
      return `<circle cx="${wx}" cy="${wheelY}" r="${wheelR * 0.62}" fill="${c.shade}" opacity="0.9"/>`;
    }
    let s = '';
    for (let i = 0; i < w.spokes; i++) {
      const a = (i / w.spokes) * Math.PI * 2;
      const x1 = wx + Math.cos(a) * wheelR * 0.2;
      const y1 = wheelY + Math.sin(a) * wheelR * 0.2;
      const x2 = wx + Math.cos(a) * wheelR * 0.62;
      const y2 = wheelY + Math.sin(a) * wheelR * 0.62;
      s += `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="${c.shade}" stroke-width="${wheelR * 0.12}" stroke-linecap="round" opacity="0.85"/>`;
    }
    return s;
  };

  const wheel_ = (wx) => `
    <circle cx="${wx}" cy="${wheelY}" r="${wheelR}" fill="${PALETTE.ink}"/>
    <circle cx="${wx}" cy="${wheelY}" r="${wheelR * 0.72}" fill="#20262e"/>
    ${spokes(wx)}
    <circle cx="${wx}" cy="${wheelY}" r="${wheelR * 0.16}" fill="${c.spec}" opacity="0.5"/>`;

  // Body: a fastback coupe silhouette via a smooth path.
  const bodyTop = baseY - carH;
  const roofY = bodyTop - carH * 0.62;
  const body = `
    M ${x0} ${baseY}
    C ${x0 + carW * 0.02} ${bodyTop + carH * 0.1}, ${x0 + carW * 0.1} ${bodyTop}, ${x0 + carW * 0.2} ${bodyTop - carH * 0.05}
    C ${x0 + carW * 0.32} ${roofY + carH * 0.1}, ${x0 + carW * 0.42} ${roofY}, ${x0 + carW * 0.56} ${roofY}
    C ${x0 + carW * 0.7} ${roofY}, ${x0 + carW * 0.82} ${bodyTop - carH * 0.02}, ${x0 + carW * 0.92} ${bodyTop + carH * 0.18}
    C ${x0 + carW * 0.98} ${bodyTop + carH * 0.4}, ${x0 + carW} ${baseY - carH * 0.2}, ${x0 + carW} ${baseY}
    Z`;

  // Glasshouse (greenhouse) inset.
  const glass = `
    M ${x0 + carW * 0.26} ${bodyTop - carH * 0.02}
    C ${x0 + carW * 0.36} ${roofY + carH * 0.18}, ${x0 + carW * 0.44} ${roofY + carH * 0.1}, ${x0 + carW * 0.55} ${roofY + carH * 0.1}
    C ${x0 + carW * 0.66} ${roofY + carH * 0.1}, ${x0 + carW * 0.74} ${bodyTop - carH * 0.04}, ${x0 + carW * 0.78} ${bodyTop + carH * 0.12}
    L ${x0 + carW * 0.28} ${bodyTop + carH * 0.12}
    Z`;

  return Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
  <defs>
    <linearGradient id="wall" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${PALETTE.wallTop}"/>
      <stop offset="1" stop-color="${PALETTE.wallBottom}"/>
    </linearGradient>
    <linearGradient id="floor" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${PALETTE.floorTop}"/>
      <stop offset="1" stop-color="${PALETTE.floorBottom}"/>
    </linearGradient>
    <radialGradient id="keylight" cx="0.5" cy="0.28" r="0.7">
      <stop offset="0" stop-color="${PALETTE.keylight}" stop-opacity="0.9"/>
      <stop offset="1" stop-color="${PALETTE.keylight}" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="bodyGrad" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${c.spec}"/>
      <stop offset="0.42" stop-color="${c.body}"/>
      <stop offset="1" stop-color="${c.shade}"/>
    </linearGradient>
    <radialGradient id="contact" cx="0.5" cy="0.5" r="0.5">
      <stop offset="0" stop-color="${PALETTE.contactInk}" stop-opacity="0.5"/>
      <stop offset="0.7" stop-color="${PALETTE.contactInk}" stop-opacity="0.15"/>
      <stop offset="1" stop-color="${PALETTE.contactInk}" stop-opacity="0"/>
    </radialGradient>
  </defs>

  <!-- studio: seamless wall-to-floor -->
  <rect x="0" y="0" width="${width}" height="${baseY + wheelR}" fill="url(#wall)"/>
  <rect x="0" y="${baseY - wheelR * 0.2}" width="${width}" height="${height - baseY + wheelR}" fill="url(#floor)"/>
  <rect x="0" y="0" width="${width}" height="${height}" fill="url(#keylight)"/>

  <!-- the signature track-line on the studio floor -->
  <rect x="0" y="${baseY + wheelR * 1.5}" width="${width}" height="2" fill="${PALETTE.accent}" opacity="0.5"/>
  <rect x="${cx - carW * 0.5}" y="${baseY + wheelR * 1.5}" width="${carW}" height="2" fill="${PALETTE.accent}" opacity="0.9"/>

  <!-- soft contact shadow under the car -->
  <ellipse cx="${cx}" cy="${baseY + wheelR * 0.95}" rx="${carW * 0.52}" ry="${wheelR * 0.5}" fill="url(#contact)"/>

  <!-- car body -->
  <path d="${body}" fill="url(#bodyGrad)"/>
  <!-- body highlight crease -->
  <path d="M ${x0 + carW * 0.08} ${baseY - carH * 0.46} C ${x0 + carW * 0.4} ${baseY - carH * 0.6}, ${x0 + carW * 0.7} ${baseY - carH * 0.6}, ${x0 + carW * 0.94} ${baseY - carH * 0.4}" stroke="${c.spec}" stroke-width="2" fill="none" opacity="0.35"/>
  <!-- glasshouse -->
  <path d="${glass}" fill="${PALETTE.ink}" opacity="0.82"/>
  <path d="${glass}" fill="${c.spec}" opacity="0.08"/>
  <!-- accent light blade along the rocker -->
  <rect x="${x0 + carW * 0.1}" y="${baseY - carH * 0.08}" width="${carW * 0.8}" height="3" rx="1.5" fill="${PALETTE.accent}" opacity="0.55"/>

  <!-- wheels -->
  ${wheel_(frontWX)}
  ${wheel_(rearWX)}

  <!-- unobtrusive placeholder provenance marker (bottom-right) -->
  <text x="${width - 18}" y="${height - 16}" text-anchor="end" font-family="sans-serif" font-size="${Math.round(height * 0.018)}" fill="${PALETTE.ink}" opacity="0.28" letter-spacing="2">PLACEHOLDER RENDER</text>
  ${label ? `<text x="18" y="${height - 16}" font-family="sans-serif" font-size="${Math.round(height * 0.018)}" fill="${PALETTE.ink}" opacity="0.3" letter-spacing="2">${label}</text>` : ''}
</svg>`);
}

async function render(svg, outPath, width, height) {
  await mkdir(dirname(outPath), { recursive: true });
  await sharp(svg, { density: 200 })
    .resize(width, height, { fit: 'cover' })
    .avif({ quality: 62, effort: 6 })
    .toFile(outPath);
}

/**
 * Render one full stage pass (hero crops + the colour×wheel matrix) for a given
 * register. `light` writes to the canonical paths the mocks already reference;
 * `dark` writes the dark-stage re-key into `*-dark` / `matrix-dark/` so the
 * dark theme gets a night studio, not a light car on a dark page.
 */
async function renderStage(register) {
  PALETTE = PALETTES[register];
  const suffix = register === 'dark' ? '-dark' : '';
  const matrixDir = register === 'dark' ? 'matrix-dark' : 'matrix';

  // 1) The hero LCP render (default config: Glacier White + Aero) — two crops.
  const desktop = studioSvg({
    width: 1600,
    height: 900,
    color: 'col-glacier',
    wheel: 'whl-aero',
    label: 'APEX LUMEN GT',
  });
  await render(desktop, join(RENDERS_DIR, `hero${suffix}.avif`), 1600, 900);
  await render(
    desktop,
    join(RENDERS_DIR, `hero-desktop${suffix}.avif`),
    1920,
    1080,
  );

  const mobile = studioSvg({
    width: 900,
    height: 1100,
    color: 'col-glacier',
    wheel: 'whl-aero',
    label: 'APEX LUMEN GT',
  });
  await render(mobile, join(RENDERS_DIR, `hero-mobile${suffix}.avif`), 900, 1100);

  // 2) The colour x wheel matrix stills (Tier-3 fallback source — small set).
  let count = 0;
  for (const colorId of Object.keys(COLORS)) {
    for (const wheelId of Object.keys(WHEELS)) {
      const svg = studioSvg({
        width: 1400,
        height: 1000,
        color: colorId,
        wheel: wheelId,
        label: `${COLORS[colorId].name} / ${WHEELS[wheelId].name}`,
      });
      const file = `${colorId}__${wheelId}.avif`;
      await render(svg, join(RENDERS_DIR, matrixDir, file), 1400, 1000);
      count++;
    }
  }
  return count;
}

async function main() {
  const lightCount = await renderStage('light');
  const darkCount = await renderStage('dark');

  // Wheel preview thumbnails for the swatch UI (light register — they sit on a
  // light/dark-neutral swatch chip).
  PALETTE = PALETTES.light;
  for (const wheelId of Object.keys(WHEELS)) {
    const svg = wheelThumbSvg(wheelId);
    await render(svg, join(RENDERS_DIR, 'wheels', `${wheelId.replace('whl-', '')}.avif`), 200, 200);
  }

  // A tiny blur-placeholder data URI for the hero <Image> (CLS-safe).
  const blur = await sharp(studioSvg({ width: 160, height: 90, color: 'col-glacier', wheel: 'whl-aero', label: '' }), { density: 72 })
    .resize(16, 9, { fit: 'cover' })
    .avif({ quality: 40 })
    .toBuffer();
  await writeFile(
    join(RENDERS_DIR, 'hero-blur.txt'),
    `data:image/avif;base64,${blur.toString('base64')}`,
    'utf8',
  );

  console.log(
    `Generated light (${lightCount}) + dark (${darkCount}) matrix stills + hero crops + wheel thumbs + blur into public/renders/lumen-gt/`,
  );
}

/** A small isolated wheel illustration for the configurator swatch. */
function wheelThumbSvg(wheelId) {
  const w = WHEELS[wheelId] ?? WHEELS['whl-aero'];
  const cx = 100;
  const cy = 100;
  const r = 78;
  let spokes = '';
  if (w.spokes === 0) {
    spokes = `<circle cx="${cx}" cy="${cy}" r="${r * 0.6}" fill="#20262e"/>`;
  } else {
    for (let i = 0; i < w.spokes; i++) {
      const a = (i / w.spokes) * Math.PI * 2;
      spokes += `<line x1="${cx + Math.cos(a) * r * 0.18}" y1="${cy + Math.sin(a) * r * 0.18}" x2="${cx + Math.cos(a) * r * 0.6}" y2="${cy + Math.sin(a) * r * 0.6}" stroke="#cfd6dd" stroke-width="${r * 0.11}" stroke-linecap="round"/>`;
    }
  }
  return Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="200" height="200" viewBox="0 0 200 200">
    <rect width="200" height="200" fill="#eef1f4"/>
    <circle cx="${cx}" cy="${cy}" r="${r}" fill="${PALETTE.ink}"/>
    <circle cx="${cx}" cy="${cy}" r="${r * 0.72}" fill="#2a313a"/>
    ${spokes}
    <circle cx="${cx}" cy="${cy}" r="${r * 0.15}" fill="${PALETTE.accent}" opacity="0.7"/>
  </svg>`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
